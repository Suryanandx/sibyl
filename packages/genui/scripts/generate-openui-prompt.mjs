// Regenerates src/openui-library-prompt.generated.ts from the OpenUI chat
// component library, so the Gateway can embed the exact component contract the
// browser renders with (@openuidev/react-ui openuiChatLibrary).
//
// Run after upgrading @openuidev/react-ui:  pnpm --filter @open-gpt-live/genui generate
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { openuiChatLibrary, openuiChatPromptOptions } = await import(
  "@openuidev/react-ui/genui-lib"
);

// The preamble placeholder is replaced at runtime by buildGenUiSystemPrompt().
const PREAMBLE_TOKEN = "{{OPEN_GPT_LIVE_PREAMBLE}}";
const prompt = openuiChatLibrary.prompt({
  ...openuiChatPromptOptions,
  preamble: PREAMBLE_TOKEN
});

const out = resolve(here, "../src/openui-library-prompt.generated.ts");
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/generate-openui-prompt.mjs — do not edit.\n` +
    `// Source: @openuidev/react-ui openuiChatLibrary (root: ${openuiChatLibrary.root})\n` +
    `export const OPENUI_PREAMBLE_TOKEN = ${JSON.stringify(PREAMBLE_TOKEN)};\n` +
    `export const OPENUI_LIBRARY_ROOT = ${JSON.stringify(openuiChatLibrary.root)};\n` +
    `export const OPENUI_LIBRARY_PROMPT = ${JSON.stringify(prompt)};\n`
);
console.log(`Wrote ${out} (${prompt.length} chars)`);
