/**
 * The site's shared header and footer, taken from apps/site/index.html (between the
 * site:header / site:footer markers), with their links rewritten for a page that lives
 * one folder down (docs/, products/). The docs builder and the product page builder
 * both use it, so every page has the same chrome as the landing page.
 */
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

export const SITE = join(dirname(fileURLToPath(import.meta.url)), "..");
export const REPO = join(SITE, "..", "..");
export const GITHUB = "https://github.com/Suryanandx/sibyl";

export const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Landing-relative links -> links that work from /<folder>/<page>.html. */
export function fromFolder(html, folder) {
  return html.replace(/(href|src)="([^"]*)"/g, (m, attr, url) => {
    if (/^(https?:|mailto:)/.test(url)) return m;
    if (url.startsWith("#")) return `${attr}="../index.html${url}"`;
    if (url === `${folder}/` || url === `${folder}/index.html`) return `${attr}="index.html"`;
    if (url.startsWith(`${folder}/`)) return `${attr}="${url.slice(folder.length + 1)}"`;
    if (url === "./" || url === "") return `${attr}="../index.html"`;
    return `${attr}="../${url}"`;
  });
}

/** Header and footer HTML for pages in `folder`. */
export function chrome(folder) {
  const landing = readFileSync(join(SITE, "index.html"), "utf8");
  const between = (start, end) => {
    const a = landing.indexOf(start);
    const b = landing.indexOf(end);
    if (a < 0 || b < 0) throw new Error(`index.html is missing ${start} / ${end}`);
    return landing.slice(a + start.length, b);
  };
  return {
    header: fromFolder(between("<!-- site:header -->", "<!-- /site:header -->"), folder),
    footer: fromFolder(between("<!-- site:footer -->", "<!-- /site:footer -->"), folder)
  };
}

/** The <head> every sub-page shares (stylesheets and scripts one folder up). */
export function head({ title, description, generatedFrom, extraCss = [], extraJs = [] }) {
  return `<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}" />
  <meta name="color-scheme" content="light dark" />
  <meta name="theme-color" content="#f7f7f5" media="(prefers-color-scheme: light)" />
  <meta name="theme-color" content="#161817" media="(prefers-color-scheme: dark)" />
  <!-- Generated by ${esc(generatedFrom)}. Do not edit by hand. -->
  <link rel="icon" type="image/png" href="../assets/brand/sibyl-mark-light.png" />
  <link rel="preload" as="font" type="font/woff2" href="../assets/fonts/archivo-latin-wght-normal.woff2" crossorigin />
  <script>
    try { var t = localStorage.getItem("sibyl-site-theme"); if (t === "light" || t === "dark") document.documentElement.dataset.theme = t; } catch (e) {}
  </script>
  <link rel="stylesheet" href="../site.css" />
${extraCss.map((href) => `  <link rel="stylesheet" href="${href}" />\n`).join("")}  <script src="../site.js" defer></script>
${extraJs.map((src) => `  <script src="${src}" defer></script>\n`).join("")}</head>`;
}
